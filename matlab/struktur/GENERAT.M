    uicontrol(h_fig,...             % Pushbutton gain stark erhoehen
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',5,...
        'tag','generator',...
        'callback','generat(''gain'');',...
        'string','>>',...         
        'backgroundcolor',farbe,...
        'position',[links+0.18 unten+0.01 0.05 0.04]);



    % ---- Bediengruppe Quantisierung ------------------------------------------------
    sys_data = get...               % Lies Systemdaten aus userdata
      (h_sys_filterung,'userdata');
