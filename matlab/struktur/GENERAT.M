        'units','normalized',...
        'tag','phase',...
        'string','Phase',...
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.01 unten+0.05 0.11 0.04]);
    uicontrol(h_fig,...             % Pushbutton Phase verringern
        'style','pushbutton',...     
        'units','normalized',...
        'tag','phase',...
        'callback','generat(''phase'');',...
        'string','<',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.12 unten+0.05 0.04 0.04]);
    phase = sys_data(2,5);          % Phase in Grad
    string = [num2str(phase)]; % String erzeugen
    uicontrol(h_fig,...             % Text fuer eingestellte phase 
        'style','edit',...    
        'units','normalized',...
        'tag','phase',...
        'string',string,...    
        'visible','off',...
        'callback','generat(''phase'');',...
        'backgroundcolor',[1 1 1],...
        'position',[links+0.16 unten+0.05 0.06 0.04]);
    uicontrol(h_fig,...             % Text fuer eingestellte phase 
        'style','text',...    
        'units','normalized',...
        'tag','phase',...
        'string','ø',...    
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.22 unten+0.05 0.03 0.04]);
    uicontrol(h_fig,...             % Pushbutton phase stark erhoehen
        'style','pushbutton',...     
        'units','normalized',...
        'tag','phase',...
        'callback','generat(''phase'');',...
        'string','>',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.25 unten+0.05 0.04 0.04]);
    uicontrol(h_fig,...             % Ueberschrift fuer Schrittweite 
        'style','text',...    
        'units','normalized',...
        'tag','phase_step',...
        'string','Step:+/-',...
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.01 unten+0.01 0.11 0.04]);
    uicontrol(h_fig,...             % Pushbutton Schrittweite verringern
        'style','pushbutton',...     
        'units','normalized',...
        'tag','phase_step',...
        'callback','generat(''step_phase'');',...
        'string','<',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.12 unten+0.01 0.04 0.04]);
    uicontrol(h_fig,...             % Text fuer eingestellte Schrittweite 
        'style','edit',...    
        'units','normalized',...
        'tag','phase_step',...
        'string',10,...    
        'userdata',10,...
        'visible','off',...
        'callback','generat(''step_phase'');',...
        'backgroundcolor',[1 1 1],...
        'position',[links+0.16 unten+0.01 0.09 0.04]);
    uicontrol(h_fig,...             % Pushbutton Phase stark erhoehen
        'style','pushbutton',...     
        'units','normalized',...
        'tag','phase_step',...
        'callback','generat(''step_phase'');',...
        'string','>',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.25 unten+0.01 0.04 0.04]);
    if funktion == 4                % Wenn Sinusfunktion
      h_objekt = findobj...         % Finde Objekte mit der Bezeichnung 
        ('tag','frequenz');         % 'frequenz'
      set(h_objekt,'visible','on'); % Setze Objekte sichtbar
      h_objekt = findobj...         % Finde Objekte mit der Bezeichnung 
        ('tag','frequenz_step');    % 'frequenz_step'
      set(h_objekt,'visible','on'); % Setze Objekte sichtbar
      h_objekt = findobj...         % Finde Objekte mit der Bezeichnung 
        ('tag','phase');            % 'phase'
      set(h_objekt,'visible','on'); % Setze Objekte sichtbar
      h_objekt = findobj...         % Finde Objekte mit der Bezeichnung 
        ('tag','phase_step');       % 'phase_step'
      set(h_objekt,'visible','on'); % Setze Objekte sichtbar
    end

    % ---- Bediengruppe Offset ----------------------------------------------
    links = 0.03;
    unten = 0.53;
    uicontrol(h_fig,...             % Rahmen fuer Bedienelemente Offset
        'style','frame',...
        'units','normalized',...
        'tag','generator',...
        'backgroundcolor',farbe,...
        'position',[links unten 0.26 0.1]);
    uicontrol(h_fig,...             % Ueberschrift fuer Offseteinstellung 
        'style','text',...    
        'units','normalized',...
        'tag','generator',...
        'string','Offset',...    
        'HorizontalAlignment','left',...
        'backgroundcolor',farbe,...
        'position',[links+0.03 unten+0.05 0.15 0.04]);
    offset = sys_data(2,2);
    uicontrol(h_fig,...             % Text fuer eingestellten Offset 
        'style','text',...    
        'units','normalized',...
        'tag','offset',...
        'string',offset,...    
        'backgroundcolor',farbe,...
        'HorizontalAlignment','right',...
        'position',[links+0.13 unten+0.05 0.09 0.04]);
    uicontrol(h_fig,...             % Pushbutton offset stark verringern
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',-0.5,...
        'tag','generator',...
        'callback','generat(''offset'');',...
        'string','<<',...         
        'backgroundcolor',farbe,...
        'position',[links+0.03 unten+0.01 0.05 0.04]);
    uicontrol(h_fig,...             % Pushbutton offset verringern
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',-0.1,...
        'tag','generator',...
        'callback','generat(''offset'');',...
        'string','<',...         
        'backgroundcolor',farbe,...
        'position',[links+0.08 unten+0.01 0.05 0.04]);
    uicontrol(h_fig,...             % Pushbutton offset erhoehen
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',0.1,...
        'tag','generator',...
        'callback','generat(''offset'');',...
        'string','>',...         
        'backgroundcolor',farbe,...
        'position',[links+0.13 unten+0.01 0.05 0.04]);
    uicontrol(h_fig,...             % Pushbutton offset stark erhoehen
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',0.5,...
        'tag','generator',...
        'callback','generat(''offset'');',...
        'string','>>',...         
        'backgroundcolor',farbe,...
        'position',[links+0.18 unten+0.01 0.05 0.04]);


    % ---- Bediengruppe gain ------------------------------------------------
    links = 0.03;
    unten = 0.42;
    uicontrol(h_fig,...             % Rahmen fuer Bedienelemente gain
        'style','frame',...
        'units','normalized',...
        'tag','generator',...
        'backgroundcolor',farbe,...
        'position',[links unten 0.26 0.1]);
    uicontrol(h_fig,...             % Ueberschrift Verstaerkungseinstellung 
        'style','text',...    
        'units','normalized',...
        'tag','generator',...
        'string','Gain',...    
        'HorizontalAlignment','left',...
        'backgroundcolor',farbe,...
        'position',[links+0.03 unten+0.05 0.11 0.04]);
    gain = num2str(sys_data(2,3));
    gain = [gain, ' dB'];
    uicontrol(h_fig,...             % Text fuer eingestellte Verstaerkung 
        'style','text',...    
        'units','normalized',...
        'tag','gain',...
        'string',gain,...    
        'backgroundcolor',farbe,...
        'HorizontalAlignment','right',...
        'position',[links+0.13 unten+0.05 0.09 0.04]);
    uicontrol(h_fig,...             % Pushbutton gain stark verringern
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',-5,...
        'tag','generator',...
        'callback','generat(''gain'');',...
        'string','<<',...         
        'backgroundcolor',farbe,...
        'position',[links+0.03 unten+0.01 0.05 0.04]);
    uicontrol(h_fig,...             % Pushbutton gain verringern
        'style','pushbutton',...    % 
        'units','normalized',...
        'userdata',-0.5,...
        'tag','generator',...
        'callback','generat(''gain'');',...
        'string','<',...         
