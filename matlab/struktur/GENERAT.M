function generat(command_str)
% Generator
%
% Die Funktion stellt einen Funktionsgenerator dar, mit dem die
% Eingangsfolge, mit der das System beaufschlagt wird, beeinflusst wird
% 
% Funktionsaufruf
%   generat
%
%
% ------------------- Funktions Header --------------------------------------
% Autor:               Jörg Rose / Roman Ußkurat
% Erstellungsdatum:    7-10/97
% Version:             MATLAB Version 5 / Student Edition
% 
% Betreuer: Prof. Dr.-Ing. Stark
%


% ------------------------- Globale Variablen -------------------------------

farbe = [0.752 0.752 0.752];



% -------------- Initialisierung --------------------------------------------
if nargin == 0                      % wenn kein Parameter uebergeben
  command_str = 'init';             % setze command_str = init
end                                 % Ende von nargin == 0

% ------------------ init ---------------------------------------------------
if strcmp(command_str,'init')       % Wenn command_str = 'init'
  figure_exists = 0;                % Figur existiert nicht
  fig_help = 0;                     % Hilfsvariable
  h_figure = get(0,'children');     % Finde Handles der exestierenden Figuren
  for handle = h_figure'            % lokale Variable handle wird mit den
                                    % Werten des h_axes Vektors beaufschlagt
    fig_help = strcmp(get(handle,'tag'),...
                     'fcn_generator');
    if fig_help == 1                % Wenn ein Objekt die Kennzeichnung
      figure_exists = 1;            % 'fcn_generator' aufweist, setze
    end                             % figure_exists auf 1
  end                               % Ende von for handle = h_axes'

  if ~figure_exists
    h_fig=figure('units','normalized',...% Einheit normalisiert
        'menubar','none',...        % Menueleiste ausblenden
        'position',[0 0 1 0.96],...
        'color',[1 1 1],...         % Farbe = Weiss
        'numbertitle','off',...     % Figurnummer ausblenden
        'name','Funktionsgenerator',...% Titelzeile der Figur
        'visible','off',...
        'tag','fcn_generator');

    uicontrol(h_fig,...              % Rahmen oben
        'style','frame',...
        'units','normalized',...
        'tag','generator',...
        'backgroundcolor',farbe,...
        'position',[0.32 0.92 0.65 0.08]);
    uicontrol(h_fig,...              % Rahmen rechts
        'style','frame',...
        'units','normalized',...
        'tag','generator',...
        'backgroundcolor',farbe,...
        'position',[0.97 0 0.03 1]);
    uicontrol(h_fig,...             % Rahmen links
        'style','frame',...
        'units','normalized',...
        'tag','generator',...
        'backgroundcolor',farbe,...
        'position',[0 0 0.32 1]);
    uicontrol(h_fig,...             % Rahmen unten
        'style','frame',...
        'units','normalized',...
        'tag','generator',...
        'backgroundcolor',farbe,...
        'position',[0.32 0 0.65 0.55]);
    pause(0.01);
    uicontrol(h_fig,...             % Pushbutton zum schliessen
        'style','pushbutton',...    
        'units','normalized',...
        'tag','generator',...
        'callback','generat(''closed'');',...
        'string','OK',...         
        'backgroundcolor',farbe,...
        'position',[0.7 0.05 0.1 0.045]);
    uicontrol(h_fig,...             % Pushbutton fuer Hilfe
        'style','pushbutton',...    
        'units','normalized',...
        'tag','generator',...
        'callback','!winhelp struktur\Generat.hlp',... % Bei Betätigung
        'string','Hilfe',...         
        'backgroundcolor',farbe,...
        'position',[0.8 0.05 0.1 0.045]);

    h_sys_filterung = findobj...    % Finde Pushbutton 'filterung'
      ('tag','filterung');
    old_sys_data = get...           % Lies Systemdaten aus userdata
      (h_sys_filterung,'userdata');

    uicontrol(h_fig,...             % Pushbutton zum schliessen
        'style','pushbutton',...    % ohne Uebername der Eingangsfolge
        'units','normalized',...
        'tag','cancel',...
        'userdata',old_sys_data,... % Speichere alte Eingangsfolge
        'callback','generat(''cancel'');',...
        'string','Abbruch',...         
        'backgroundcolor',farbe,...
        'position',[0.7 0.095 0.1 0.045]);

    % ---- Bediengruppe FFT-Laenge ------------------------------------------
    links = 0.34;
    unten = 0.94;
    string_value = str2mat('16',... % Erzeuge string fuer Popupmenue
      '32','64','128','256','512','1024'); % 'fft_laenge'
    h_sys_filterung = findobj...      % Finde Pushbutton 'filterung'
      ('tag','filterung');
    sys_data = get...               % Lies Systemdaten aus userdata
      (h_sys_filterung,'userdata');
    fft_laenge = sys_data(2,1);     % FFT-Laenge = 2.Reihe, 1.Spalte
    value=log(fft_laenge)/log(2)-3; % Ermittle Popupvalue aus FFT-Laenge
    uicontrol(h_fig,...             % Popupmenue fuer FFT-laenge
        'style','popupmenu',...    
        'units','normalized',...
        'userdata',1,...            % Kennzeichen fuer FFT-laenge
        'backgroundcolor',[1 1 1],... % Hintergrundfarbe = Weiss
        'tag','fft_laenge',...
        'value',value,...
        'callback','generat(''fft_change'');',...
        'string',string_value,...   % Menuepunkte
        'position',[links+0.15 unten 0.08 0.04]);
    uicontrol(h_fig,...             % Ueberschrift fuer Popupmenue 
        'style','text',...    
        'units','normalized',...
        'tag','generator',...
        'string','FFT-Länge',...   % 
        'backgroundcolor',farbe,...
        'position',[links unten 0.15 0.04]);

    % ---- Bediengruppe Funktionstyp ----------------------------------------
    links = 0.57;
    unten = 0.94;
    string_value = str2mat...       % Erzeuge string fuer Popupmenue
      ('Einheitsimpuls',... 
       'Einheitssprungfolge',...
       'Rampenfolge',...
       'Sinusfolge',...
       'Fouriersynthese',...
       'Rechteckfolge');
    funktion = sys_data(2,6);       % Funktionstyp = 2.Reihe, 6.Spalte
    uicontrol(h_fig,...             % Popupmenue fuer Funktionstyp
        'style','popupmenu',...    
        'units','normalized',...
        'backgroundcolor',[1 1 1],... % Hintergrundfarbe = Weiss
        'tag','funktion',...
        'callback','generat(''funktion_change'');',...
        'string',string_value,...   % Menuepunkte
        'value',funktion,...
        'position',[links+0.15 unten 0.22 0.04]);
    uicontrol(h_fig,...             % Ueberschrift fuer Popupmenue 
        'style','text',...    
        'units','normalized',...
        'tag','generator',...
        'string','Funktion',...   % 
        'backgroundcolor',farbe,...
        'position',[links unten 0.15 0.04]);


    % ---- Bediengruppe Frequenz --------------------------------------------
    links = 0.33;
    unten = 0.38;
    uicontrol(h_fig,...             % Rahmen fuer Bedienelemente Frequenz
        'style','frame',...
        'units','normalized',...
        'tag','frequenz',...
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links unten 0.3 0.1]);
    uicontrol(h_fig,...             % Ueberschrift fuer Frequenzeinstellung 
        'style','text',...    
        'units','normalized',...
        'tag','frequenz',...
        'string','Frequenz',...
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.01 unten+0.05 0.11 0.04]);
    uicontrol(h_fig,...             % Pushbutton Frequenz verringern
        'style','pushbutton',...     
        'units','normalized',...
        'userdata',-0.0001,...
        'tag','frequenz',...
        'callback','generat(''frequenz'');',...
        'string','<',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.12 unten+0.05 0.04 0.04]);
    ny = sys_data(2,4);             % Normierte Frequenz
    uicontrol(h_fig,...             % Text fuer eingestellte Frequenz 
        'style','edit',...    
        'units','normalized',...
        'tag','frequenz',...
        'string',ny,...    
        'callback','generat(''frequenz'');',...
        'visible','off',...
        'backgroundcolor',[1 1 1],...
        'position',[links+0.16 unten+0.05 0.09 0.04]);
    uicontrol(h_fig,...             % Pushbutton Frequenz stark erhoehen
        'style','pushbutton',...     
        'units','normalized',...
        'tag','frequenz',...
        'callback','generat(''frequenz'');',...
        'string','>',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.25 unten+0.05 0.04 0.04]);
    uicontrol(h_fig,...             % Ueberschrift fuer Schrittweite 
        'style','text',...    
        'units','normalized',...
        'tag','frequenz_step',...
        'string','Step:+/-',...
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.01 unten+0.01 0.11 0.04]);
    uicontrol(h_fig,...             % Pushbutton Schrittweite verringern
        'style','pushbutton',...     
        'units','normalized',...
        'tag','frequenz_step',...
        'callback','generat(''step_freq'');',...
        'string','<',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.12 unten+0.01 0.04 0.04]);
    uicontrol(h_fig,...             % Text fuer eingestellte Schrittweite 
        'style','edit',...    
        'units','normalized',...
        'tag','frequenz_step',...
        'string',0.001,...    
        'userdata',0.001,...
        'visible','off',...
        'callback','generat(''step_freq'');',...
        'backgroundcolor',[1 1 1],...
        'position',[links+0.16 unten+0.01 0.09 0.04]);
    uicontrol(h_fig,...             % Pushbutton Frequenz stark erhoehen
        'style','pushbutton',...     
        'units','normalized',...
        'tag','frequenz_step',...
        'callback','generat(''step_freq'');',...
        'string','>',...         
        'visible','off',...
        'backgroundcolor',farbe,...
        'position',[links+0.25 unten+0.01 0.04 0.04]);


    % ---- Bediengruppe Phase -----------------------------------------------
    links = 0.33;
    unten = 0.27;
    uicontrol(h_fig,...             % Rahmen fuer Bedienelemente Frequenz
        'style','frame',...
        'units','normalized',...
        'tag','phase',...
        'visible','off',...
        'backgroundcolor',farbe,...
