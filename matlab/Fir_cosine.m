    if fo_b1>0 & fo_b1<fu_b2 & fu_b2<fo_b2 & fo_b2<fu_b3 & fu_b3<0.5
       %**dann keine Fehlermeldung!****
    else
      fehler('','Normierte Bandgrenzen im Bereich:  0<f/fa<0.5 !',...
             'Die Frequenzbänder dürfen sich nicht überschneiden.');
      hilfsgroesse=1;     %**Hiermit wird verhindert, daß das Fenster sich schließt**
    end;
  end;

  %*********************************************************%
  %          wenn kein Fehler aufgetreten...                %
  % Übernehmen der Filterart u. den entspr. Grenzfrequenzen %
  %*********************************************************%

  if hilfsgroesse==0  % wenn kein Fehler aussen
    if get(cosine_tiefpass_radio,'value')==1,    %**Tiefpass**
      FT_cosine='TP';
      OBERE_BG_BAND1=get(obere_bg_band1_edit,'String');
      UNTERE_BG_BAND2=get(untere_bg_band2_edit,'String');
      M=[1 1 0 0];
      F=[0 str2num(get(obere_bg_band1_edit,'String'))*2 str2num(get(untere_bg_band2_edit,'String'))*2 1];

      [b,a]=firrcos(n,(F(2)+F(3))/2,F(3)-F(2),2);

    elseif get(cosine_hochpass_radio,'value')==1,   %**Hochpass**
      FT_cosine='HP';
      OBERE_BG_BAND1=get(obere_bg_band1_edit,'String');
      UNTERE_BG_BAND2=get(untere_bg_band2_edit,'String');
      M=[0 0 1 1];
      F=[0 str2num(get(obere_bg_band1_edit,'String'))*2 str2num(get(untere_bg_band2_edit,'String'))*2 1];

      [b,a]=firrcos(n,(F(2)+F(3))/2,F(3)-F(2),2);
      b=-b; b(n/2+1)=b(n/2+1)+1;

    elseif get(cosine_bandpass_radio,'value')==1,   %**Bandpass**
      FT_cosine='BP';
      OBERE_BG_BAND1=get(obere_bg_band1_edit,'String');
      UNTERE_BG_BAND2=get(untere_bg_band2_edit,'String');
      OBERE_BG_BAND2=get(obere_bg_band2_edit,'String');
      UNTERE_BG_BAND3=get(untere_bg_band3_edit,'String');
      M=[0 0 1 1 0 0];
      F=[0 str2num(get(obere_bg_band1_edit,'String'))*2 str2num(get(untere_bg_band2_edit,'String'))*2  str2num(get(obere_bg_band2_edit,'String'))*2 str2num(get(untere_bg_band3_edit,'String'))*2 1];

      [btp,a]=firrcos(n,(F(2)+F(3))/2,F(3)-F(2),2);
      [bhp,a]=firrcos(n,(F(4)+F(5))/2,F(5)-F(4),2);
      bhp=-bhp; bhp(n/2+1)=bhp(n/2+1)+1;
      b=bhp+btp; b=-b; b(n/2+1)=b(n/2+1)+1;

    elseif get(cosine_bandsperre_radio,'value')==1,   %**Bandsperre**
      FT_cosine='BS';
      OBERE_BG_BAND1=get(obere_bg_band1_edit,'String');
      UNTERE_BG_BAND2=get(untere_bg_band2_edit,'String');
      OBERE_BG_BAND2=get(obere_bg_band2_edit,'String');
      UNTERE_BG_BAND3=get(untere_bg_band3_edit,'String');
      M=[1 1 0 0 1 1];
      F=[0 str2num(get(obere_bg_band1_edit,'String'))*2 str2num(get(untere_bg_band2_edit,'String'))*2  str2num(get(obere_bg_band2_edit,'String'))*2 str2num(get(untere_bg_band3_edit,'String'))*2 1];

      [btp,a]=firrcos(n,(F(2)+F(3))/2,F(3)-F(2),2);
      [bhp,a]=firrcos(n,(F(4)+F(5))/2,F(5)-F(4),2);
      bhp=-bhp; bhp(n/2+1)=bhp(n/2+1)+1;
      b=bhp+btp;

    end;

    %******************************************************%
    % folgende Zeilen beseitigen Nullstellen im Unendlichen%
    %******************************************************%
    indx=find(abs(b)<1e-4);  % quick & dirty
    b(indx)=b(indx)*0;

    %**********************%
    % Dateiname übernehmen %
    %**********************%
    filename=get(cosine_filename_edit,'String');
    filtertyp=11; % Erkennungsvariable für raised cosine-Methode

    %****************************%
    %  Speichern des Datensatzes %
    %****************************%
    pos=max(findstr(filename,'\'));
    if ~isempty(pos), fname=filename(pos+1:length(filename));
    else fname=filename; end

    h=length(fname);
    g=abs(fname);
    k=findstr(fname,'.');
    g= g<45|g>122|(g>45&g<48&g~=46)|(g>57&g<65)|(g>90&g<95)|g==96;

    if h>12| nnz(g)~=0 | h==0 | k>9 | isempty(k) | h-k > 3
      %Überprüfung ob Dateiname zu lang
      %Überprüfung auf Sonderzeichen
      %gültig:Buchstaben,Zahlen,Binde- u.
      %Unterstrich.

      fehler('','DATEINAMENFORMAT:','max. 8 Zeichen',...
            'erlaubt sind: Buchstaben,Zahlen,Binde- u. Unterstrich');
      hilfsgroesse=1; %**Hiermit wird verhindert, daß das Fenster sich schließt**

    end;

    if hilfsgroesse==0    %**wenn keine Fehler innen
      %*********************************************************%
      %  Erstellen und Speichern der zugehörigen Protokolldatei %
      %*********************************************************%

      fid=fopen(filename,'wt');
      fprintf(fid,'Protokoll   -Digitale Filter unter MATLAB 4.x-      %s\n\n\n',date);
      fprintf(fid,'Filtertyp: FIR-Filter,%s\n\n',FT_cosine);
      fprintf(fid,'Entwurfsverfahren: Raised cosine-Approximation\n\n');
      fprintf(fid,'Filterordnung N:%3.0f\n\n',n);

      if strcmp(FT_cosine,'HP') |strcmp(FT_cosine,'TP') |strcmp(FT_cosine,'AP')
        fprintf(fid,'Band 1: \n\t');
        fprintf(fid,'normierte untere Bandgrenze: 0.00000\n\t');
        fprintf(fid,'normierte obere  Bandgrenze: %s\n\t',OBERE_BG_BAND1);
        fprintf(fid,'Band 2: \n\t');
        fprintf(fid,'normierte untere Bandgrenze: %s\n\t',UNTERE_BG_BAND2);
        fprintf(fid,'normierte obere  Bandgrenze: 0.50000\n\t');
      else
        fprintf(fid,'Band 1: \n\t');
        fprintf(fid,'normierte untere Bandgrenze: 0.00000\n\t');
        fprintf(fid,'normierte obere  Bandgrenze: %s\n\t',OBERE_BG_BAND1);
        fprintf(fid,'Band 2: \n\t');
        fprintf(fid,'normierte untere Bandgrenze: %s\n\t',UNTERE_BG_BAND2);
        fprintf(fid,'normierte obere  Bandgrenze: %s\n\t',OBERE_BG_BAND2);
        fprintf(fid,'Band 3: \n\t');
        fprintf(fid,'normierte untere Bandgrenze: %s\n\t',UNTERE_BG_BAND3);
        fprintf(fid,'normierte obere  Bandgrenze: 0.50000\n\t');
      end;

      fprintf(fid,'berechnete Filterkoeffizienten:\n\n');
      for n=[0:length(b)-1]
          fprintf(fid,'b(%3.0f) = %+2.16f\n',n,b(n+1));
      end
      fprintf(fid,' \n\na(  0) = +1.0\n\n\n\n'); %Leerzeilen erzeugen

      %*** Pol- u. Nullstellen***************************

      fprintf(fid,'Nullstellen: \n\n');
      fprintf(fid,'   Realteil       Imaginärteil         Betrag     Phase    Anz.\n');
      fprintf(fid,'===============================================================\n');
      z=roots(b);               %Nullstellen berechnen
      [mults,idx]=mpoles(z);    %Nullstellen nach
      z_w=z(idx);               %Größe sortiern.

      real_z=real(z_w);  %Realteil
      imag_z=imag(z_w);  %Imaginärteil
      r=abs(z_w);        %Betrag
      phi=(atan2(imag(z_w),real(z_w)))*360/(2*pi);  %Phase

      %****Abfrage nach mehrfach vorkommenenden Nullstellen*********
      for i=1:length(z_w)
        if i==1                  %Abfrage 1.Wert
          zaehler=1;
          if length(z_w)==1
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_z(i),imag_z(i),r(i),phi(i),zaehler);
          end;
        elseif i==length(z_w) & length(z_w)>1    %Abfrage letzter Wert
          if abs(z_w(i)-z_w(i-1))<0.001
            zaehler=zaehler+1;
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_z(i-1),imag_z(i-1),r(i-1),phi(i-1),zaehler);
          else
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_z(i-1),imag_z(i-1),r(i-1),phi(i-1),zaehler);
            zaehler=1;
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_z(i),imag_z(i),r(i),phi(i),zaehler);
          end;
        else
          if abs(z_w(i)-z_w(i-1))<0.001  %toleranz=0.001 !
            zaehler=zaehler+1;
          else
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_z(i-1),imag_z(i-1),r(i-1),phi(i-1),zaehler);
            zaehler=1;     %Zähler zurücksetzen
          end;
        end;
      end;

      fprintf(fid,' \n\n'); %Leerzeilen erzeugen
      fprintf(fid,'Polstellen: \n\n');
      fprintf(fid,'   Realteil       Imaginärteil         Betrag     Phase    Anz.\n');
      fprintf(fid,'===============================================================\n');
      p=roots(a);               %Polstellen berechnen
      if isempty(p),                 %Fall: FIR-Filter!
        p=zeros(size(b,2)-1,1);
      end;
      [mults,idx]=mpoles(p);   %Polstellen nach
      p_w=p(idx);               %Größe sortiern.

      real_p=real(p_w);  %Realteil
      imag_p=imag(p_w);  %Imaginärteil
      r=abs(p_w);        %Betrag
      phi=(atan2(imag(p_w),real(p_w)))*360/(2*pi);  %Phase

      %****Abfrage nach mehrfach vorkommenenden Polstellen*********
      for i=1:length(p_w)
        if i==1                  %Abfrage 1.Wert
          zaehler=1;
          if length(p_w)==1
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_p(i),imag_p(i),r(i),phi(i),zaehler);
          end;
        elseif i==length(p_w) & length(p_w)>1    %Abfrage letzter Wert
          if abs(p_w(i)-p_w(i-1))<0.001
            zaehler=zaehler+1;
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_p(i-1),imag_p(i-1),r(i-1),phi(i-1),zaehler);
          else
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_p(i-1),imag_p(i-1),r(i-1),phi(i-1),zaehler);
            zaehler=1;
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_p(i),imag_p(i),r(i),phi(i),zaehler);
          end;
        else
          if abs(p_w(i)-p_w(i-1))<0.001  %toleranz=0.001 !
            zaehler=zaehler+1;
          else
            fprintf(fid,'%13.6f  %13.6f    %13.6f  %10.3f  %3.0f\n',real_p(i-1),imag_p(i-1),r(i-1),phi(i-1),zaehler);
            zaehler=1;     %Zähler zurücksetzen
          end;
        end;
      end;
      fclose(fid);

      %***************************************************************%
      % Dialogfeld schliessen und nicht mehr nötige Variablen löschen %
      %***************************************************************%
      close(cosine_fir_fig);
      clear global cosine_fir_fig...
      cosine_filename_edit...
      cosine_pushbutton_ok ...
      window_push_button_abbrechen...
      cosine_bandsperre_radio cosine_hochpass_radio...
      cosine_bandpass_radio cosine_tiefpass_radio...
      ueberschrift_band1...
      ueberschrift_band2...
      cosine_ueberschrift_band3_text...
      filterord_edit...
      untere_bg_band1_edit...
      obere_bg_band1_edit cosine_ubg1_text...
      cosine_obere1_text...
      cosine_band1_frame cosine_untere_bg_band2_text...
      cosine_obere_bg_band2_text untere_bg_band2_edit...
      obere_bg_band2_edit untere_bg_band3_text...
      cosine_band2_frame obere_bg_band3_text...
      untere_bg_band3_edit...
      obere_bg_band3_edit cosine_band3_frame

      %************************************************%
      %  Aufruf des jeweiligen Moduls mit neuen Werten %
      %************************************************%

      drawmain(b,a,filename);
    end;  % kein Fehler innen
  end;    %von kein Fehler aussen
end;      % strcmp(action)

